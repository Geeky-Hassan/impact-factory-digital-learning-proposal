it('compares the demo and working-pilot scopes while keeping both estimates visible', async () => {
  const user=userEvent.setup();
  render(<NextSteps />);
  expect(screen.getByText('£2,500–£3,500')).toBeTruthy();
  expect(screen.getByText('2–3 weeks')).toBeTruthy();
  expect(screen.getByText('£7,500–£12,000')).toBeTruthy();
  expect(screen.getByText('Around 2 months')).toBeTruthy();
  expect(screen.getByRole('tabpanel').textContent).toContain('not a live learner service');
  const demo=screen.getByRole('tab',{name:/Concept demo/});
  demo.focus();
  await user.keyboard('{ArrowRight}');
  expect(screen.getByRole('tab',{name:/Working pilot/}).getAttribute('aria-selected')).toBe('true');
  expect(screen.getByRole('tabpanel').textContent).toContain('30–50 learners');
  expect(screen.getByRole('tabpanel').textContent).toContain('One live AI roleplay');
  expect(screen.getByText('£2,500–£3,500')).toBeTruthy();
  await user.click(demo);
  expect(screen.getByRole('tabpanel').textContent).toContain('scripted roleplay');
  expect(screen.getByRole('tabpanel').textContent).not.toContain('30–50 learners');
  expect(screen.getByText('Refine, extend or stop.')).toBeTruthy();
  expect(screen.queryByText(/£20k|£35k|£1,000–£2,500/)).toBeNull();
});
