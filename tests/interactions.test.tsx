it('opens qualified evidence and searches the shared source register', async () => {
  const user=userEvent.setup();
  render(<SourceProvider><SourceButton id="S06" /><SourcesButton /></SourceProvider>);
  await user.click(screen.getByRole('button',{name:/View source:/}));
  const dialog=screen.getByRole('dialog');
  expect(within(dialog).getByText(/retrospective LinkedIn post mentions 4,100/)).toBeTruthy();
  expect(within(dialog).getByRole('link',{name:/Read original source/}).getAttribute('rel')).toBe('noreferrer');
  await user.click(screen.getByRole('button',{name:'All sources'}));
  await user.type(screen.getByRole('searchbox',{name:'Search sources'}),'nonsense987');
  expect(screen.getByRole('status').textContent).toContain('No matching sources');
  await user.clear(screen.getByRole('searchbox',{name:'Search sources'}));
  await user.type(screen.getByRole('searchbox',{name:'Search sources'}),'Indicative demo');
  expect(within(dialog).getByRole('button',{name:/Indicative demo and pilot/})).toBeTruthy();
  await user.click(screen.getByRole('button',{name:'Close sources'}));
  expect(screen.queryByRole('dialog')).toBeNull();
});
